function ar_build_report()
% Self-contained HTML report: report_template.html (this folder) wrapped in a
% document skeleton (UTF-8, viewport) with the figures embedded as data URIs.
% Output: results\V1_HC_remapping_report.html (opens in any browser)
P = ar_setup();
code_dir = fileparts(mfilename('fullpath'));
fid = fopen(fullfile(code_dir, 'report_template.html'), 'r', 'n', 'UTF-8');
body = fread(fid, '*char')'; fclose(fid);
figs = {'fig1', fullfile(P.results, 'report', 'fig1_drift.png'); ...
    'fig2', fullfile(P.results, 'population', 'bayes_multinomial', 'timecourse_toward_upcoming.png'); ...
    'fig3', fullfile(P.results, 'report', 'fig3_grey.png'); ...
    'fig4', fullfile(P.results, 'report', 'fig4_onset.png'); ...
    'fig5a', fullfile(P.results, 'trial_prediction', 'cross_time_bayes_multinomial.png'); ...
    'fig5b', fullfile(P.results, 'report', 'fig5_trial.png'); ...
    'fig6', fullfile(P.results, 'theta_mua', 'theta_mua.png'); ...
    'fig7', fullfile(P.results, 'grey_coupling', 'grey_coupling.png'); ...
    'fig8', fullfile(P.results, 'theta_phase', 'theta_phase_speed5.png'); ...
    'fig9', fullfile(P.results, 'grey_lag', 'grey_lag.png'); ...
    'fig10', fullfile(P.results, 'theta_flicker', 'theta_flicker_summary.png'); ...
    'fig11', fullfile(P.results, 'theta_flicker', 'examples', 'session_16.png'); ...
    'fig12', fullfile(P.results, 'trial_prediction', 'onset_reset.png'); ...
    'fig13', fullfile(P.results, 'carryover_cells', 'carryover_cells.png')};
for k = 1:size(figs, 1)
    fid = fopen(figs{k, 2}, 'r'); bytes = fread(fid, Inf, '*uint8'); fclose(fid);
    body = strrep(body, ['{{' figs{k, 1} '}}'], ['data:image/png;base64,' matlab.net.base64encode(bytes)]);
end
html = ['<!doctype html>' newline '<html lang="en">' newline '<head>' newline '<meta charset="utf-8">' newline ...
    '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">' newline ...
    '<style>*,*::before,*::after{box-sizing:border-box}body{margin:0}img{max-width:100%}</style>' newline ...
    '</head>' newline '<body>' newline body newline '</body>' newline '</html>' newline];
out = fullfile(P.results, 'V1_HC_remapping_report.html');
fid = fopen(out, 'w', 'n', 'UTF-8'); fprintf(fid, '%s', html); fclose(fid);
fprintf('Saved %s (%.1f MB)\n', out, numel(html) / 1e6);
end
